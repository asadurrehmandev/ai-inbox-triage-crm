def _fold(group: str) -> int:
    if group not in FOLDS:
        raise KeyError(group)
    return FOLDS[group]


def _typo(text: str) -> str:
    chars = list(text)
    for index in range(1, len(chars) - 1):
        if chars[index].islower() and chars[index + 1].islower():
            chars[index], chars[index + 1] = chars[index + 1], chars[index]
            return "".join(chars)
    return text


def _sign(text: str, index: int) -> str:
    name, desk = _AUTHORS[index % len(_AUTHORS)]
    closing = _CLOSINGS[index % len(_CLOSINGS)]
    return f"{text.rstrip()}\n\n{closing}\n{name}\n{desk}\n"


def _quote(text: str, index: int = 0) -> str:
    cited = "\n".join("> " + line if line else ">" for line in text.splitlines())
    intro = _INTROS[index % len(_INTROS)]
    return f"{intro}\n\nOn the earlier note:\n{cited}\n"


def _row(group: str, label: str, text: str, urgent: int, negated: int, ask: str) -> dict:
    return {
        "group": group,
        "fold": _fold(group),
        "heldout": _fold(group) == 0,
        "label": label,
        "text": text,
        "urgent": urgent,
        "negated": negated,
        "ask": ask,
    }


def _expand(group: str, label: str, texts: list[str], urgent: int = 0, negated: int = 0, ask: str = "none") -> list[dict]:
    built: list[dict] = []
    for index, text in enumerate(texts):
        variants = [text, _sign(text, index)]
        if index % 2 == 0:
            variants.append(_quote(text, index))
        else:
            variants.append(_typo(text))
        if index % 3 == 0:
            variants.append(_sign(_quote(text, index + 3), index + 1))
        for variant in variants:
            built.append(_row(group, label, variant, urgent, negated, ask))
    return built


